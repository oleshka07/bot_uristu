"""Що саме сказати Claude Code для кожного виду задачі, і який профіль MCP дати.

Профіль обмежує ``tools/list`` до 5–8 інструментів: менше схем у контексті —
менше квоти на кожен запуск. Промпт коротки й наказовий: воркер працює без
людини, тож «покажи власнику і спитай» тут не працює — усе через інструменти.
"""

from __future__ import annotations

COMMON = (
    "Ти працюєш у фоні для персонального CRM власника, без людини в чаті. "
    "Використовуй лише інструменти crm_*. Нічого не вигадуй: пиши тільки те, "
    "що є в памʼяті системи. Тексти для людей — мовою співрозмовника, без "
    "емодзі, без лестощів. Наприкінці відповіді — один рядок: що зробив."
)


def build(kind: str, payload: dict) -> tuple[str, str]:
    """(prompt, profile)."""
    if kind == "draft_reply":
        return (
            f"Заповни чернетку відповіді #{payload.get('draft_id')}. Кроки: "
            "1) crm_get_pending_reply з цим номером — там вхідне повідомлення і "
            "памʼять про людину; 2) crm_get_owner_voice; 3) напиши відповідь у "
            "голосі власника, 1–3 речення, тією ж мовою, що й вхідне; "
            "4) crm_fill_reply_draft з текстом. Якщо вхідне — лише ввічливе "
            "завершення розмови, передай текст [SKIP].",
            "reply",
        )
    if kind == "triage_inbox":
        return (
            "Розбери пошту. 1) crm_list_untriaged_emails; для кожного листа "
            "виріши, чи він чекає відповіді власника (розсилки, сповіщення, "
            "автовідповіді — ні), терміновість (high лише коли є дедлайн або "
            "людина чекає давно) і про що він у 5–12 словах, і запиши через "
            "crm_triage_email. 2) Для листів, що потребують відповіді і ще без "
            "чернетки: crm_get_email, за потреби crm_get_contact_memory, "
            "crm_get_owner_voice, напиши відповідь і збережи crm_save_email_draft. "
            "Нічого не надсилай.",
            "inbox",
        )
    if kind == "consolidate":
        return (
            "Онови памʼять про людей. crm_list_contacts_to_consolidate — для "
            "кожного: crm_get_contact_memory, потім напиши досьє 120–200 слів "
            "(хто це, стан і траєкторія стосунку, 2–3 речі, які варто памʼятати "
            "при спілкуванні; лише з даних) і збережи crm_save_dossier; окремі "
            "сталі факти (роль, роботодавець, місто, інтереси, сімʼя) — "
            "crm_add_fact. Не дублюй факти, які вже є в памʼяті.",
            "memory",
        )
    if kind == "social_digest":
        return (
            f"Прочитай нові дописи контакту #{payload.get('contact_id')} через "
            "crm_list_unprocessed_posts. Сталі факти про людину — crm_add_fact. "
            "Події, з приводу яких доречно написати їй найближчими днями "
            "(запуск, нагорода, нова робота, дитина, переїзд) — crm_add_life_event. "
            "Селфі, цитати, реклама — ні те, ні інше. Наприкінці обовʼязково "
            "crm_mark_posts_processed з цим контактом.",
            "social",
        )
    if kind == "coach_question":
        return (
            f"Постав питання дня по цілі. crm_get_pending_coach_question "
            f"{payload.get('checkin_id')} — там ціль, статус і журнал. Ти коуч: "
            "коротко, по суті, без лестощів; одне питання, максимум два речення; "
            "якщо в журналі є записи — спирайся на останній. Збережи через "
            "crm_set_coach_question.",
            "coach",
        )
    if kind == "coach_review":
        return (
            f"Розбери відповідь власника по цілі. crm_get_checkin_to_review "
            f"{payload.get('checkin_id')}. Витягни суть у 3–15 слів (summary); "
            "статус став тільки якщо зі слів це однозначно (зробив → done, майже → "
            "almost, почав → in progress, скасував/переніс → відповідний), інакше "
            "порожньо; reply — коротка реакція без похвали, одне-два речення. "
            "Збережи через crm_record_checkin_review.",
            "coach",
        )
    if kind == "weekly_verdict":
        tone = (
            "Тиждень пройшов без жодного руху. Скажи це прямо, без помʼякшення, "
            "і назви одну дію на понеділок."
            if payload.get("stalled")
            else "Дай короткий вердикт: що реально зрушило, де провал, одна дія на понеділок."
        )
        return (
            "Надішли власнику підсумок тижня. crm_get_week_block віддасть готові "
            f"цифри. {tone} Два-три речення. Потім crm_send_owner_message з "
            "повним текстом: цифри, потім порожній рядок, потім вердикт.",
            "coach",
        )
    return (f"Невідомий вид задачі {kind}. Нічого не роби.", "reply")
